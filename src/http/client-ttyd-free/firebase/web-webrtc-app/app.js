// CALLER BUTTON ACTION
// ==========================================
document.getElementById('createBtn').addEventListener('click', async () => {
    statusDiv.innerText = "Status: Generating Local Offer...";
    
    // Gather caller network addresses and write to Firebase instantly
    pc.onicecandidate = async (event) => {
        if (event.candidate && roomId) {
            console.log(`[CALLER ICE GATHERED]:`, event.candidate.candidate);
            const candRef = doc(collection(db, 'rooms', roomId, 'callerCandidates'));
            await setDoc(candRef, event.candidate.toJSON());
        }
    };

    const offerDescription = await pc.createOffer();
    await pc.setLocalDescription(offerDescription);

    const offer = {
        sdp: offerDescription.sdp,
        type: offerDescription.type,
    };

    console.log("--- CALLER SDP OFFER CREATED ---");
    console.log(offer.sdp);

    const roomRef = await addDoc(collection(db, 'rooms'), { offer });
    roomId = roomRef.id;
    roomIdDisplay.innerText = roomId;
    statusDiv.innerText = "Status: Room open. Awaiting remote peer answer map...";

    // Start listening for callee candidates IMMEDIATELY upon room validation
    onSnapshot(collection(db, 'rooms', roomId, 'calleeCandidates'), (snapshot) => {
        snapshot.docChanges().forEach(async (change) => {
            if (change.type === 'added') {
                const data = change.doc.data();
                console.log("[CALLER ADDING REMOTE ICE CANDIDATE]:", data.candidate);
                try {
                    await pc.addIceCandidate(new RTCIceCandidate(data));
                } catch (e) {
                    console.error("Error adding remote candidate to caller:", e);
                }
            }
        });
    });

    onSnapshot(roomRef, async (snapshot) => {
        const data = snapshot.data();
        if (!pc.currentRemoteDescription && data?.answer) {
            console.log("--- RECEIVED CALLEE SDP ANSWER FROM FIRESTORE ---");
            console.log(data.answer.sdp);
            const rtcAnswerDescription = new RTCSessionDescription(data.answer);
            await pc.setRemoteDescription(rtcAnswerDescription);
        }
    });
});

