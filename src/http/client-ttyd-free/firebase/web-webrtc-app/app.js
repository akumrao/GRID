// CALLEE BUTTON ACTION
// ==========================================
document.getElementById('joinBtn').addEventListener('click', async () => {
    roomId = document.getElementById('roomInput').value.trim();
    if (!roomId) return alert("Please enter a valid Room ID first!");

    statusDiv.innerText = `Status: Fetching Room ${roomId}...`;
    const roomRef = doc(db, 'rooms', roomId);
    const roomSnapshot = await getDoc(roomRef);

    if (!roomSnapshot.exists()) {
        statusDiv.innerText = "Status: Room code not found in Cloud database.";
        return;
    }

    // Gather callee network addresses and write to Firebase instantly
    pc.onicecandidate = async (event) => {
        if (event.candidate) {
            console.log(`[CALLEE ICE GATHERED]:`, event.candidate.candidate);
            const candRef = doc(collection(db, 'rooms', roomId, 'calleeCandidates'));
            await setDoc(candRef, event.candidate.toJSON());
        }
    };

    const roomData = roomSnapshot.data();
    const offerDescription = roomData.offer;
    
    console.log("--- CALLEE FETCHED HOST SDP OFFER ---");
    console.log(offerDescription.sdp);
    
    // 1. Set the Remote Description FIRST. This resolves the async race condition.
    await pc.setRemoteDescription(new RTCSessionDescription(offerDescription));

    // 2. NOW that the remote offer is safely configured, sync incoming Caller candidates
    onSnapshot(collection(db, 'rooms', roomId, 'callerCandidates'), (snapshot) => {
        snapshot.docChanges().forEach(async (change) => {
            if (change.type === 'added') {
                const data = change.doc.data();
                console.log("[CALLEE ADDING REMOTE ICE CANDIDATE]:", data.candidate);
                try {
                    await pc.addIceCandidate(new RTCIceCandidate(data));
                } catch (e) {
                    console.error("Error adding remote candidate to callee:", e);
                }
            }
        });
    });

    // 3. Formulate the local response answer profiles 
    const answerDescription = await pc.createAnswer();
    await pc.setLocalDescription(answerDescription);

    const answer = {
        type: answerDescription.type,
        sdp: answerDescription.sdp,
    };

    console.log("--- CALLEE SDP ANSWER GENERATED ---");
    console.log(answer.sdp);

    // 4. Update the cloud document to send the answer back to the caller
    await updateDoc(roomRef, { answer });
    statusDiv.innerText = "Status: Dispatched answer mapping. Building P2P path...";
});

