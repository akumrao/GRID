// Helper tool to render message packets straight onto the UI viewport
function appendToChat(message, type) {
    const msgElement = document.createElement('div');
    msgElement.classList.add('msg', type === 'local' ? 'local-msg' : 'remote-msg');
    msgElement.innerText = type === 'local' ? `You: ${message}` : `Peer: ${message}`;
    chatBox.appendChild(msgElement);
    chatBox.scrollTop = chatBox.scrollHeight; // Auto-scroll downward
}

// Function that handles the opening state events of the Data Channel lanes
function setupDataChannelListeners(channel) {
    activeDataChannel = channel;

    channel.onopen = () => {
        console.log("--> Data Channel path is now completely OPEN.");
        chatInput.disabled = false;
        sendBtn.disabled = false;
        statusDiv.innerText = "Status: DataChannel Connected! Type below.";
        statusDiv.style.color = "#2ecc71";
    };

    channel.onclose = () => {
        console.log("--> Data Channel path has been CLOSED.");
        chatInput.disabled = true;
        sendBtn.disabled = true;
        statusDiv.innerText = "Status: DataChannel Closed.";
        statusDiv.style.color = "#d63031";
    };

    channel.onmessage = (event) => {
        console.log(`[DATA CHANNEL INBOUND]: ${event.data}`);
        appendToChat(event.data, 'remote');
    };
}

