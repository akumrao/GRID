// ==========================================
// UI ACTION HOOKS: Send Message Action
// ==========================================
sendBtn.addEventListener('click', sendMessageProcessing);
chatInput.addEventListener('keypress', (e) => { if (e.key === 'Enter') sendMessageProcessing(); });

function sendMessageProcessing() {
    const text = chatInput.value.trim();
    if (!text || !activeDataChannel || activeDataChannel.readyState !== "open") return;

    // Send the raw text parameter directly over the P2P connection lane
    activeDataChannel.send(text);
    
    // Log it locally in our own chat UI box container
    appendToChat(text, 'local');
    
    chatInput.value = ""; // Flush buffer box
}

